"""
Натан любит кататься на велосипеде.
Поскольку для Натана важно поддерживать уровень жидкости в организме, он выпивает 0,5 литра в час езды на велосипеде.
Вам указывается время в часах, и вам нужно вернуть количество литров, которое выпил Натан Минилл.
Например:

время = 3 ---- > литры = 1

время = 6,7 - - - > литры = 3

время = 11,8 - > литры = 5

"""

import math

def litres(time):
    return math.floor(time * 0.5)

print(litres(3))