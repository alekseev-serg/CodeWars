"""
Компания, в которой вы работаете, только что получила контракт на создание платежного шлюза. 
Чтобы ускорить процесс, вы вызвались создать функцию, которая будет принимать плавающие значения и возвращать 
сумму в долларах и центах.

39,99 превращается в 39,99 долларов.

Остальные члены вашей команды проследят за тем, чтобы аргумент был обработан перед передачей в вашу функцию, хотя вам нужно будет учитывать добавление конечных нулей, если они отсутствуют (хотя вам не придется беспокоиться о пропущенной точке).

Примеры:

3 должно составить $3,00

3.1 должно стать $3.10
"""

def convert_to_dollars_and_cents(amount):
    """
    Преобразует плавающее значение в строку с форматом долларов и центов.
    
    Args:
        amount: сумма в виде числа с плавающей запятой
        
    Returns:
        str: сумма в формате "$X,XX"
    """
    # Форматируем сумму с двумя десятичными знаками
    return f"${amount:.2f}"


print(convert_to_dollars_and_cents(3))      # Вывод: $3.00
print(convert_to_dollars_and_cents(3.1))    # Вывод: $3.10
print(convert_to_dollars_and_cents(39.99))  # Вы